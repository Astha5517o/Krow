export function searchKaryanaMaster(query: string, limit = 20, categoryFilter?: string): KaryanaMasterItem[] {
  let source = KARYANA_MASTER_ITEMS;
  if (categoryFilter && categoryFilter !== 'all') {
    source = source.filter(
      (item) => item.category === categoryFilter || item.subCategory === categoryFilter
    );
  }

  if (!query || !query.trim()) {
    return source.slice(0, limit);
  }
  const cleanQ = query.toLowerCase().trim();
  const tokens = cleanQ.split(/\s+/).filter(Boolean);

  const scored = source.map((item) => {
    let score = 0;
    const nameLower = item.name.toLowerCase();
    const nameEnLower = item.nameEn.toLowerCase();
    const subCatLower = item.subCategory.toLowerCase();
    const catLower = item.category.toLowerCase();

    // Exact matches
    if (item.barcode && (item.barcode === cleanQ || item.barcode.endsWith(cleanQ))) {
      score += 250;
    } else if (nameLower.startsWith(cleanQ) || nameEnLower.startsWith(cleanQ)) {
      score += 100;
    } else if (nameLower.includes(cleanQ) || nameEnLower.includes(cleanQ)) {
      score += 60;
    }

    // Token matching
    for (const token of tokens) {
      if (nameLower.includes(token)) score += 20;
      if (nameEnLower.includes(token)) score += 20;
      if (item.keywords.some((k) => k.toLowerCase().includes(token))) score += 25;
      if (subCatLower.includes(token)) score += 15;
      if (catLower.includes(token)) score += 10;
      if (item.barcode && item.barcode.includes(token)) score += 80;
    }

    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.item);
}

/**
 * Get all unique main categories from the master catalog
 */
export function getKaryanaMasterCategories(): string[] {
  const cats = Array.from(new Set(KARYANA_MASTER_ITEMS.map((i) => i.category)));
  return cats;
}

/**
 * Get all unique subcategories grouped by category
 */
export function getKaryanaSubCategoriesByCategory(): Record<string, string[]> {
  const map: Record<string, Set<string>> = {};
  for (const item of KARYANA_MASTER_ITEMS) {
    if (!map[item.category]) {
      map[item.category] = new Set();
    }
    map[item.category].add(item.subCategory);
  }
  const result: Record<string, string[]> = {};
  for (const cat in map) {
    result[cat] = Array.from(map[cat]);
  }
  return result;
}
