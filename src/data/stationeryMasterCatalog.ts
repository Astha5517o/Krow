/**
 * Fast search utility across stationery master items with barcode priority.
 */
export function searchStationeryMaster(
  query: string,
  limit = 20,
  categoryFilter?: string
): KaryanaMasterItem[] {
  let source = STATIONERY_MASTER_ITEMS;
  if (categoryFilter && categoryFilter !== 'all') {
    source = source.filter(
      (item) => item.category === categoryFilter || item.subCategory === categoryFilter
    );
  }

  if (!query || !query.trim()) {
    return source.slice(0, limit);
  }

  const cleanQ = query.toLowerCase().trim();
  const tokens = cleanQ.split(/\s+/).filter(Boolean);

  const scored = source.map((item) => {
    let score = 0;
    const nameLower = item.name.toLowerCase();
    const nameEnLower = item.nameEn.toLowerCase();
    const subCatLower = item.subCategory.toLowerCase();
    const catLower = item.category.toLowerCase();

    // Exact barcode match gets ultimate boost
    if (item.barcode && (item.barcode === cleanQ || item.barcode.endsWith(cleanQ))) {
      score += 300;
    } else if (nameLower.startsWith(cleanQ) || nameEnLower.startsWith(cleanQ)) {
      score += 100;
    } else if (nameLower.includes(cleanQ) || nameEnLower.includes(cleanQ)) {
      score += 60;
    }

    // Token matching
    for (const token of tokens) {
      if (nameLower.includes(token)) score += 20;
      if (nameEnLower.includes(token)) score += 20;
      if (item.keywords.some((k) => k.toLowerCase().includes(token))) score += 25;
      if (subCatLower.includes(token)) score += 15;
      if (catLower.includes(token)) score += 10;
      if (item.barcode && item.barcode.includes(token)) score += 80;
    }

    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.item);
}

