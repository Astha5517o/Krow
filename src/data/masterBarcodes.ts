/**
 * Normalizes barcode numbers by trimming and removing any non-digits and leading zeros.
 */
export function normalizeBarcode(code: string): string {
  return code.trim().replace(/\D/g, '').replace(/^0+/, '');
}

/**
 * Rapid indexed barcode lookup.
 * Returns the matching master product or undefined.
 * Supports exact, normalized (leading zero variants), and flexible small-packet barcode matching.
 */
export function lookupMasterBarcode(rawCode: string): MasterProduct | undefined {
  if (!rawCode) return undefined;
  const clean = rawCode.trim();
  if (!clean) return undefined;
  const normalized = normalizeBarcode(clean);

  // 1. Exact match first (fastest)
  const exact = MASTER_BARCODE_CATALOG.find((p) => p.barcode === clean);
  if (exact) return exact;

  // 2. Normalized digits match (handles EAN/UPC leading zero variants)
  if (normalized) {
    const normMatch = MASTER_BARCODE_CATALOG.find((p) => normalizeBarcode(p.barcode) === normalized);
    if (normMatch) return normMatch;

    // 3. Suffix / prefix match for 12-digit UPC vs 13-digit EAN variants or small 8-digit EAN-8
    if (normalized.length >= 7) {
      const suffixMatch = MASTER_BARCODE_CATALOG.find((p) => {
        const pNorm = normalizeBarcode(p.barcode);
        return pNorm.endsWith(normalized) || normalized.endsWith(pNorm);
      });
      if (suffixMatch) return suffixMatch;
    }
  }

  return undefined;
}
